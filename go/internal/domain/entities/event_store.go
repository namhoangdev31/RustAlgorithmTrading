package entities

import (
	"encoding/json"
	"time"

	"github.com/google/uuid"
)

// EventStream represents a stream of domain events.
type EventStream struct {
	ID         string    `json:"id"`
	StreamType string    `json:"stream_type"`
	CreatedAt  time.Time `json:"created_at"`
}

// EventSnapshot caches historical aggregate states.
type EventSnapshot struct {
	ID            uuid.UUID       `json:"id"`
	StreamID      string          `json:"stream_id"`
	LastVersion   int64           `json:"last_version"`
	SnapshotState json.RawMessage `json:"snapshot_state"`
	CreatedAt     time.Time       `json:"created_at"`
}

// EventSchemaVersion holds historical schemas definitions for event types.
type EventSchemaVersion struct {
	ID               uuid.UUID `json:"id"`
	EventType        string    `json:"event_type"`
	Version          string    `json:"version"`
	SchemaDefinition string    `json:"schema_definition"`
}

// CommandRequest represents requests generated by client command actions.
type CommandRequest struct {
	ID          uuid.UUID       `json:"id"`
	CommandType string          `json:"command_type"`
	Payload     json.RawMessage `json:"payload"`
	UserID      *uuid.UUID      `json:"user_id"`
	CreatedAt   time.Time       `json:"created_at"`
}

// CommandResult records final status and outcome of command requests.
type CommandResult struct {
	CommandID       uuid.UUID       `json:"command_id"`
	Status          string          `json:"status"`
	ResponsePayload json.RawMessage `json:"response_payload"`
	ErrorMessage    *string         `json:"error_message"`
}

// ProjectionOffset tracks stream offsets consumed by read projections.
type ProjectionOffset struct {
	ProjectionName    string     `json:"projection_name"`
	ConsumerGroup     string     `json:"consumer_group"`
	StreamID          string     `json:"stream_id"`
	LastSeenVersion   int64      `json:"last_seen_version"`
	LastEventID       *uuid.UUID `json:"last_event_id"`
	LastSequence      *int64     `json:"last_sequence"`
	LastSchemaVersion *string    `json:"last_schema_version"`
	LastError         *string    `json:"last_error"`
	RebuildStartedAt  *time.Time `json:"rebuild_started_at"`
	UpdatedAt         time.Time  `json:"updated_at"`
}

// ProjectionError logs validation or mapping failures in projections.
type ProjectionError struct {
	ID             uuid.UUID `json:"id"`
	ProjectionName string    `json:"projection_name"`
	StreamID       string    `json:"stream_id"`
	FailedVersion  int64     `json:"failed_version"`
	ErrorMessage   string    `json:"error_message"`
	OccurredAt     time.Time `json:"occurred_at"`
}

// ReadModelVersion tracks schemas migrations version of the read models.
type ReadModelVersion struct {
	ModelName     string `json:"model_name"`
	SchemaVersion string `json:"schema_version"`
}

// ReplayJob records parameters of events replay executions.
type ReplayJob struct {
	ID           uuid.UUID `json:"id"`
	StreamID     string    `json:"stream_id"`
	StartVersion int64     `json:"start_version"`
	EndVersion   int64     `json:"end_version"`
	Status       string    `json:"status"`
}

// InboxEvent ensures idempotent incoming message processing.
type InboxEvent struct {
	ID          uuid.UUID       `json:"id"`
	MessageID   string          `json:"message_id"`
	Payload     json.RawMessage `json:"payload"`
	IsProcessed bool            `json:"is_processed"`
}

// EventStore represents the main event store partition parent.
type EventStore struct {
	EventID          uuid.UUID       `json:"event_id"`
	StreamID         string          `json:"stream_id"`
	AggregateType    string          `json:"aggregate_type"`
	AggregateID      string          `json:"aggregate_id"`
	AggregateVersion int64           `json:"aggregate_version"`
	EventType        string          `json:"event_type"`
	EventVersion     int             `json:"event_version"`
	SchemaVersion    string          `json:"schema_version"`
	CommandID        *uuid.UUID      `json:"command_id"`
	CausationID      *uuid.UUID      `json:"causation_id"`
	CorrelationID    *uuid.UUID      `json:"correlation_id"`
	Payload          json.RawMessage `json:"payload"`
	CreatedAt        time.Time       `json:"created_at"`
}

// OutboxEvent handles transactional outbox pattern partitions.
type OutboxEvent struct {
	ID            uuid.UUID       `json:"id"`
	AggregateType string          `json:"aggregate_type"`
	AggregateID   string          `json:"aggregate_id"`
	EventType     string          `json:"event_type"`
	Payload       json.RawMessage `json:"payload"`
	IsProcessed   bool            `json:"is_processed"`
	CreatedAt     time.Time       `json:"created_at"`
}
