package entities

import (
	"encoding/json"
	"time"

	"github.com/google/uuid"
)

// EventStream represents a stream of domain events.
type EventStream struct {
	ID         string    `json:"id" gorm:"type:varchar(255);primaryKey"`
	StreamType string    `json:"stream_type" gorm:"type:varchar(100);not null"`
	CreatedAt  time.Time `json:"created_at" gorm:"not null;default:now()"`
}

// TableName overrides the default table name for EventStream.
func (EventStream) TableName() string {
	return "event_streams"
}

// EventSnapshot caches historical aggregate states.
type EventSnapshot struct {
	ID            uuid.UUID       `json:"id" gorm:"type:uuid;primaryKey;default:gen_random_uuid()"`
	StreamID      string          `json:"stream_id" gorm:"type:varchar(255);not null"`
	LastVersion   int64           `json:"last_version" gorm:"type:bigint;not null"`
	SnapshotState json.RawMessage `json:"snapshot_state" gorm:"type:jsonb;not null"`
	CreatedAt     time.Time       `json:"created_at" gorm:"not null;default:now()"`
}

// TableName overrides the default table name for EventSnapshot.
func (EventSnapshot) TableName() string {
	return "event_snapshots"
}

